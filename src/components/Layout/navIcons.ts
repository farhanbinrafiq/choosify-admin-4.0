/** Partner (seller / creator) menus use their own keys — matched by route instead. */
const PATH_ICONS: Array<[string, LucideIcon]> = [
  ['/admin/brand-studio', Palette],
  ['/admin/creator-studio', Palette],
  ['/admin/brand-profile', UserSquare2],
  ['/admin/creator-profile', UserSquare2],
  ['/admin/platform-orders', ClipboardList],
  ['/admin/customers', Users],
  ['/admin/conversations', MessageSquare],
  ['/admin/support', MessageSquare],
  ['/admin/my-earnings', PiggyBank],
  ['/admin/plan-billing', CreditCard],
];

export function navIconFor(key: string, path?: string): LucideIcon {
  if (NAV_ICONS[key]) return NAV_ICONS[key];
  const hit = path ? PATH_ICONS.find(([prefix]) => path === prefix || path.startsWith(`${prefix}/`) || path.startsWith(`${prefix}?`)) : undefined;
  return hit ? hit[1] : Circle;
}
